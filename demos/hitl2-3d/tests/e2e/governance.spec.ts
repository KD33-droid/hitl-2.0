import { expect,test,type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
const nav=(page:Page,name:string)=>page.getByRole('navigation').getByRole('button',{name,exact:true}).click()
const selected=(page:Page)=>page.getByRole('combobox',{name:'Selected decision',exact:true})
const disposition=(page:Page)=>page.locator('.current-status .run-status')
async function start(page:Page,action:string,condition:string){
  await page.getByRole('combobox',{name:'Requested action',exact:true}).selectOption(action)
  await page.getByRole('combobox',{name:'Fixture condition',exact:true}).selectOption(condition)
  await page.getByRole('button',{name:'Start decision'}).click()
  await page.getByRole('button',{name:'Run to boundary'}).click()
}
const shoot=async(page:Page,name:string)=>{
  await mkdir('screenshots/phase2',{recursive:true})
  await page.screenshot({path:`screenshots/phase2/${name}.png`,fullPage:true,animations:'disabled'})
}
test('a decision can be followed from its pending request through all four views',async({page})=>{
  test.setTimeout(90_000)
  const errors:string[]=[]
  page.on('pageerror',err=>errors.push(err.message))
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/');await nav(page,'Simulator')
  await start(page,'preview','aggregate-only')
  await start(page,'preview','detail-requested')
  await start(page,'export','outside-example-scope')
  await start(page,'release','bounded-authorised')
  await start(page,'release','elevated-authority')
  await expect(disposition(page)).toHaveText('Pending review')
  await page.getByLabel('Review rationale').fill('Request a second privileged review of this release.')
  await page.getByRole('button',{name:'Refer for further review'}).click()
  await expect(page.getByRole('region',{name:'Pending review request'})).toContainText('Q-002')
  await shoot(page,'02-simulator')
  await nav(page,'Architecture')
  await expect(selected(page)).toHaveValue('RUN-005')
  await expect(page.getByRole('heading',{name:'Human Approval Layer'})).toBeVisible()
  await expect(page.locator('.stage-caption')).toContainText('E-007')
  await expect(page.locator('.scene-label:visible')).toHaveCount(5)
  await shoot(page,'01-architecture')
  await nav(page,'Simulator')
  await page.getByLabel('Review rationale').fill('Reviewed the elevated release and its stated scope.')
  await page.getByRole('button',{name:'Approve elevated action'}).click()
  await expect(disposition(page)).toHaveText('allow')
  await expect(page.locator('.event-list li')).toHaveCount(10)
  // Presentation playback never appends events or opens a second decision.
  await page.getByRole('button',{name:'Replay history'}).click()
  await expect(page.locator('.timeline-header')).toContainText('Action proposal')
  await expect(page.locator('.review-summary')).toHaveCount(0)
  await page.getByRole('button',{name:'Pause replay'}).click()
  await page.getByRole('button',{name:'Back to latest'}).click()
  await expect(page.locator('.event-list li')).toHaveCount(10)
  await nav(page,'Dashboard')
  await expect(selected(page)).toHaveValue('RUN-005')
  await expect(page.getByRole('heading',{name:'Governance dashboard'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Inspect Decision statistics: 4 terminal decisions'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Inspect Agent activity: 5 proposals'})).toBeVisible()
  await expect(page.getByRole('region',{name:'Pending review queue'})).toContainText('1 open request')
  await shoot(page,'03-dashboard')
  await page.getByRole('button',{name:'Intervention history'}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Inspect RUN-005 E-008 in Audit'}).click()
  await expect(selected(page)).toHaveValue('RUN-005')
  await expect(page.getByRole('slider',{name:'Inspect event sequence'})).toHaveValue('8')
  await expect(page.getByRole('heading',{name:'Audit explorer'})).toBeVisible()
  await expect(page.getByText('Second privileged reviewer',{exact:false}).first()).toBeVisible()
  await page.getByRole('button',{name:'Verify full sequence'}).click()
  await expect(page.getByRole('status',{name:'Original verification result'})).toContainText('All 10 events match')
  await shoot(page,'04-audit')
  await page.getByRole('button',{name:'Edit a copy'}).click()
  await page.getByRole('combobox',{name:'Copy event',exact:true}).selectOption('7')
  await page.getByLabel('Copied logical time (UTC)').fill('2000-01-01T00:01:07.000Z')
  await page.getByRole('button',{name:'Verify edited copy'}).click()
  await expect(page.getByRole('status',{name:'Copy verification result'})).toContainText('First mismatch: E-008 · sequence 8')
  await page.getByLabel('Copy operation').selectOption('rehash')
  await expect(page.getByRole('status',{name:'Copy verification result'})).toContainText('Copy not verified')
  await page.getByRole('button',{name:'Verify edited copy'}).click()
  await expect(page.getByRole('status',{name:'Copy verification result'})).toContainText('recomputed digest differs')
  await shoot(page,'05-edited-copy')
  await page.getByRole('button',{name:'Original sequence',exact:true}).click()
  await page.getByRole('button',{name:'Verify full sequence'}).click()
  await expect(page.getByRole('status',{name:'Original verification result'})).toContainText('All 10 events match')
  await nav(page,'Dashboard')
  await expect(page.getByRole('button',{name:'Inspect Decision statistics: 4 terminal decisions'})).toBeVisible()
  await page.getByRole('region',{name:'Pending review queue'}).getByRole('button',{name:'Review request'}).click()
  await expect(selected(page)).toHaveValue('RUN-004')
  await expect(disposition(page)).toHaveText('Pending review')
  await nav(page,'Simulator')
  await expect(page.getByRole('button',{name:'Confirm bounded action'})).toBeDisabled()
  await expect(page.getByRole('button',{name:'Refer for further review'})).toHaveCount(0)
  await page.getByLabel('Review rationale').fill('Confirmed this already-authorised bounded action.')
  await page.getByRole('button',{name:'Confirm bounded action'}).click()
  await expect(disposition(page)).toHaveText('allow')
  expect(errors).toEqual([])
})
test('unsupported inputs create no history; pending states survive navigation and rejection',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.clock.install()
  await page.goto('/');await nav(page,'Simulator')
  await page.getByLabel('Fixture condition').selectOption('elevated-authority')
  await expect(page.getByText('No scripted case',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Start decision'})).toBeDisabled()
  await nav(page,'Audit')
  await expect(page.getByRole('heading',{name:'No decision records yet'})).toBeVisible()
  await nav(page,'Simulator');await start(page,'release','bounded-authorised')
  await page.getByLabel('Review rationale').fill('Declined this sample release.')
  await page.clock.fastForward(24*60*60*1000)
  await expect(page.locator('.event-list li')).toHaveCount(5)
  await nav(page,'Dashboard');await expect(disposition(page)).toHaveText('Pending review')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await nav(page,'Simulator')
  await expect(page.getByLabel('Review rationale')).toHaveValue('Declined this sample release.')
  await page.getByRole('button',{name:'Reject',exact:true}).click()
  await expect(page.getByRole('button',{name:'Reject',exact:true})).toHaveCount(0)
  await expect(disposition(page)).toHaveText('deny')
  await expect(page.locator('.event-list li')).toHaveCount(8)
  await nav(page,'Audit')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
