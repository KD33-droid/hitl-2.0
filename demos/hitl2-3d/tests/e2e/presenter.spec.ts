import {expect,test} from '@playwright/test'
import {mkdir} from 'node:fs/promises'
test('offline guided rehearsal, explicit review, resets and refresh',async({page})=>{
  test.setTimeout(90000)
  await page.setViewportSize({width:1920,height:1080})
  await page.emulateMedia({reducedMotion:'reduce'})
  const external:string[]=[]
  await page.route('**/*',r=>{if(new URL(r.request().url()).hostname==='127.0.0.1')return r.continue();external.push(r.request().url());return r.abort()})
  await page.goto('/');await page.getByRole('button',{name:'Guided walkthrough'}).click()
  const g=page.getByRole('region',{name:'Presenter guide'}),next=g.getByRole('button',{name:'Next',exact:true})
  await mkdir('screenshots/phase3',{recursive:true})
  const capture=(name:string)=>page.screenshot({path:`screenshots/phase3/${name}.png`})
  await expect(page.locator('.scene-label:visible')).toHaveCount(5)
  await capture('architecture')
  await next.click();await g.getByRole('button',{name:'Previous'}).click();await next.click()
  await next.click();await next.click();await next.click()
  await expect(next).toBeDisabled();await capture('simulator')
  await page.getByLabel('Review rationale').fill('Reviewed the scripted release scope.')
  await page.getByRole('button',{name:'Approve elevated action'}).click()
  await next.click();await next.click();await capture('dashboard')
  await next.click();await page.getByRole('button',{name:'Verify full sequence'}).click()
  await expect(page.getByRole('status',{name:'Original verification result'})).toContainText('All 8 events match')
  await capture('audit');await next.click()
  await page.getByRole('button',{name:'Edit a copy'}).click()
  await page.getByRole('button',{name:'Verify edited copy'}).click()
  await expect(page.getByRole('status',{name:'Copy verification result'})).toContainText('First mismatch')
  await g.getByRole('button',{name:'Restart walkthrough'}).click()
  await expect(g).toContainText('1 OF 9');await g.getByRole('button',{name:'Exit guide'}).click()
  page.on('dialog',d=>d.accept())
  await page.getByRole('button',{name:'Reset current scenario'}).click()
  await expect(page.locator('.event-list li')).toHaveCount(1)
  await page.getByRole('button',{name:'Reset session',exact:true}).click()
  await expect(page.locator('.session-strip')).toHaveCount(0)
  await page.reload();await expect(page.getByRole('heading',{name:'Architecture explorer'})).toBeVisible()
  expect(external).toEqual([])
})
